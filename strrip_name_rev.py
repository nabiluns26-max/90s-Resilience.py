# Nama dengan whitespace di awal dan di akhir
name = "\t Priyo Utomo \n"

# Tampilkan nama asli whitespace terlihat
print ("Nama asli:")
print (name)

# lstrip() menghapus whitespace di sisi kiri
print ("lstrip():")
print (name.lstrip())

# rstrip() menghapus whitespace di sisi kanan
print ("rstrip():")
print (name.rstrip())

# strip() menghapus whitespace di kanan dan kiri
print ("strip():")
print(name.strip())